import { readStored, writeStored } from '../utils/libraryWorkspace';
import { loadWindowFrame, validWindowGroups, type WindowFrame, type WindowGroups } from '../utils/desktopLayout';
import { loadWindowConnections, loadMagnetLinks, type WindowConnections, type MagnetLinks } from '../utils/windowConnections';
import { loadContainerLayout, validContainerLayout, type ContainerLayout } from '../utils/containerLayout';

export const handleModes = ['resize', 'move', 'magnet', 'merge'] as const;
export type HandleMode = typeof handleModes[number];
export const toolNames: Record<HandleMode, string> = { resize: 'Resize', move: 'Normal Move', magnet: 'Magnet Move', merge: 'Merge Move' };
export type PanelPreferences = { handleMode: HandleMode; locked: boolean; cornerHandleHidden?: boolean; horizontal?: boolean; headerSize?: { width: number; height: number } };
export type GeneratedParent = { id: string; title: string; autoGenerated: true };
export type WorkspaceState = {
  schemaVersion: 1;
  cornerHandlesHidden?: boolean;
  workflowPlacementVersion?: number;
  workspaceId: string;
  groups: WindowGroups;
  connections: WindowConnections;
  magnets: MagnetLinks;
  layouts: Record<string, ContainerLayout>;
  frames: Record<string, WindowFrame>;
  panels: Record<string, PanelPreferences>;
  generated: GeneratedParent[];
};
const key = (page: string) => `swissmouse-desktop-v1:${page}:workspace`;
const safe = (id: unknown): id is string => typeof id === 'string' && !!id && !['__proto__', 'prototype', 'constructor', '$content'].includes(id);
const record = (v: unknown): Record<string, any> => v && typeof v === 'object' && !Array.isArray(v) ? v : {};
const frameValid = (v: any): v is WindowFrame => v && ['x', 'y', 'width', 'height'].every(k => Number.isFinite(v[k])) && v.width > 0 && v.height > 0;
export function validWorkspaceState(page: string, raw: unknown): WorkspaceState {
  const value = record(raw);
  const v = value.schemaVersion === 1 && value.workspaceId === page ? value : {};
  const entries = (name: string) => Object.entries(record(v[name])).filter(([id]) => safe(id)).slice(0, 256);
  return {
    schemaVersion: 1, workspaceId: page, ...(v.workflowPlacementVersion === 1 ? { workflowPlacementVersion: 1 } : {}), cornerHandlesHidden: v.cornerHandlesHidden !== false,
    groups: validWindowGroups(v.groups),
    connections: Object.fromEntries(entries('connections').filter(([, c]) => c && safe(c.parent) && ['left','right','top','bottom','header'].includes(c.side) && Number.isFinite(c.order))),
    magnets: Array.isArray(v.magnets) ? v.magnets.filter((p: any): p is [string, string] => Array.isArray(p) && p.length === 2 && p.every((id: unknown) => typeof id === 'string' && safe(id)) && p[0] !== p[1]).slice(0, 256) : [],
    layouts: Object.fromEntries(entries('layouts').map(([id, layout]) => [id, validContainerLayout(layout)])),
    frames: Object.fromEntries(entries('frames').filter(([, frame]) => frameValid(frame)).map(([id, f]) => [id, { x: f.x, y: f.y, width: f.width, height: f.height }])),
    panels: Object.fromEntries(entries('panels').map(([id, p]) => [id, { handleMode: handleModes.includes(p?.handleMode) ? p.handleMode : 'resize', locked: p?.locked === true, ...(Number.isFinite(p?.headerSize?.width) && Number.isFinite(p?.headerSize?.height) ? { headerSize: { width: Math.max(48, Math.min(680, p.headerSize.width)), height: Math.max(48, Math.min(500, p.headerSize.height)) } } : {}), ...(typeof p?.horizontal === 'boolean' ? { horizontal: p.horizontal } : {}), ...(typeof p?.cornerHandleHidden === 'boolean' ? { cornerHandleHidden: p.cornerHandleHidden } : {}) }])),
    generated: Array.isArray(v.generated) ? [...new Map<string, GeneratedParent>(v.generated.filter((p: any) => p && typeof p.id === 'string' && /^generated-parent-[a-zA-Z0-9-]+$/.test(p.id) && typeof p.title === 'string').slice(0, 64).map((p: any) => [p.id, { id: p.id, title: p.title.slice(0, 100), autoGenerated: true as const }])).values()] : [],
  };
}
/** Import existing keys once. The atomic workspace envelope then owns layout
 * writes; legacy keys remain available for recovery and are cleared by Reset. */
export function loadWorkspaceState(page: string): WorkspaceState {
  const saved = readStored<unknown>(key(page), null);
  if (saved && record(saved).schemaVersion === 1 && record(saved).workspaceId === page) return validWorkspaceState(page, saved);
  const state = validWorkspaceState(page, null);
  state.groups = loadWindowGroupsLegacy(page);
  state.connections = loadWindowConnections(page); state.magnets = loadMagnetLinks(page);
  try {
    const prefix = `swissmouse-desktop-v1:${page}:`;
    for (const storedKey of Object.keys(localStorage).filter(k => k.startsWith(prefix))) {
      const id = storedKey.slice(prefix.length);
      if (id.startsWith('container:')) state.layouts[id.slice(10)] = loadContainerLayout(page, id.slice(10));
      else if (safe(id)) { const frame = loadWindowFrame(page, id); if (frame) state.frames[id] = frame; }
    }
  } catch { /* Storage is optional; layout editing still works in memory. */ }
  return validWorkspaceState(page, state);
}
function loadWindowGroupsLegacy(page: string) {
  return validWindowGroups(readStored(`swissmouse-desktop-v1:${page}:groups`, {}));
}
export const saveWorkspaceState = (state: WorkspaceState) => writeStored(key(state.workspaceId), state);

/** Bounded, in-memory history. Snapshots contain layout only, never book data. */
export class LayoutHistory {
  past: WorkspaceState[] = [];
  future: WorkspaceState[] = [];
  checkpoint(state: WorkspaceState) { this.past = [...this.past.slice(-29), state]; this.future = []; }
  undo(state: WorkspaceState) { const next = this.past.pop(); if (next) this.future.push(state); return next; }
  redo(state: WorkspaceState) { const next = this.future.pop(); if (next) this.past.push(state); return next; }
}
