import { readProjectState, writeProjectState, rejectProjectWrites } from './project-store-fixture';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync, spawn } from 'node:child_process';
import { fingerprint, writeAudioMetadata } from './audio-engine';
import { audiobookTags } from './audiobook-metadata';
import { extendedMetadata } from '../src/utils/extendedMetadata';

test('Inbox reconciliation, persisted settings, completion, verified moves, rollback, and active paths', async () => {
  const root = fs.mkdtempSync(path.join(process.cwd(), 'inbox-test-'));
  const inbox = path.join(root, 'Inbox'), library = path.join(root, 'Library'), source = path.join(inbox, 'Book');
  const bin = path.join(root, 'runtime', 'bin');
  fs.mkdirSync(source, { recursive: true }); fs.mkdirSync(library); fs.mkdirSync(bin, { recursive: true });
  const tool = (name: string) => {
    const configured = process.env[`TEST_${name.toUpperCase()}`];
    const candidate = configured || path.resolve('runtime', 'bin', name + (process.platform === 'win32' ? '.exe' : ''));
    return fs.existsSync(candidate) ? candidate : execFileSync(process.platform === 'win32' ? 'where.exe' : 'which', [name], { encoding: 'utf8' }).trim().split(/\r?\n/)[0];
  };
  const ffmpeg = tool('ffmpeg'), ffprobe = tool('ffprobe');
  for (const [name, binary] of [['ffmpeg', ffmpeg], ['ffprobe', ffprobe]]) {
    const dest = path.join(bin, name + (process.platform === 'win32' ? '.exe' : ''));
    try { fs.linkSync(binary, dest); } catch { fs.copyFileSync(binary, dest); }
  }
  const meta = { title: 'Verified Book', author: 'Writer', narrator: 'Reader', genres: ['Fiction'], tags: ['Keep'], language: 'eng', abridged: false, explicit: false, description: 'Keep this description' };
  fs.writeFileSync(path.join(source, 'metadata.json'), JSON.stringify(meta));
  const ffmeta = path.join(root, 'chapters.txt');
  fs.writeFileSync(ffmeta, ';FFMETADATA1\n[CHAPTER]\nTIMEBASE=1/1000\nSTART=0\nEND=2000\ntitle=One\n');
  const audio = path.join(source, 'original.m4b');
  execFileSync(ffmpeg, ['-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', '-i', ffmeta, '-map_metadata', '1', '-map_chapters', '1', '-c:a', 'aac', audio], { windowsHide: true });
  const originalBytes = fs.readFileSync(audio);
  const exportFolder = path.join(inbox, '.swissmouse-work', 'exports');
  fs.mkdirSync(exportFolder, { recursive: true });
  const output = path.join(exportFolder, 'finished.m4b'); fs.copyFileSync(audio, output);
  fs.writeFileSync(path.join(exportFolder, 'metadata.json'), JSON.stringify(meta));
  const job = { associatedFiles: [{ path: path.join(exportFolder, 'metadata.json'), kind: 'metadata' }], id: 'existing-book', name: meta.title, metadata: meta, metadataDraft: { ...meta, description: 'Unfinished draft' }, createdAt: new Date().toISOString(), source: { kind: 'inbox', mode: 'folder', path: source }, sourceFolderPath: source, sourceKey: await fingerprint([audio], {}), outputFolderPath: path.dirname(exportFolder), parts: [{ id: 'p1', name: 'original.m4b', sizeBytes: fs.statSync(audio).size, durationSeconds: 2, bitrate: 64, order: 1 }], totalDurationSeconds: 2, totalSizeBytes: fs.statSync(audio).size, status: 'built', mergedMp3: { filename: 'original.m4b', fullPath: audio, duration: 2, bitrate: 64, sizeBytes: fs.statSync(audio).size }, chapters: [{ id: 'c1', start: '00:00:00.000', end: '00:00:02.000', title: 'One' }], candidates: [], logs: [], outputM4b: { filename: 'finished.m4b', fullPath: output, duration: 2, sizeBytes: fs.statSync(output).size, bitrate: '64k', chaptersCount: 1, codec: 'aac', format: 'm4b' }, exports: [{ format: 'm4b', status: 'success', progress: 100, fullPath: output, filename: 'finished.m4b' }], exportedFiles: { m4b: output } };
  await writeAudioMetadata({ ffmpeg, ffprobe, file: output, format: 'm4b', tags: audiobookTags(meta, undefined, {}, 'm4b') });
  fs.writeFileSync(path.join(exportFolder, 'exmetadata.json'), JSON.stringify(extendedMetadata(meta, job.chapters, job.id)));
  fs.writeFileSync(path.join(root, 'jobs.json'), JSON.stringify([job]));
  fs.writeFileSync(path.join(root, 'config.json'), JSON.stringify({ inbox_folder: inbox, library_folder: library, library_template: '%Book Title%', ffmpeg_path: ffmpeg, ffprobe_path: ffprobe }));
  const port = 47000 + Math.floor(Math.random() * 1000), base = `http://127.0.0.1:${port}`;
  let server: ReturnType<typeof spawn>;
  const request = async (route: string, body?: unknown, expected = 200) => {
    const response = await fetch(base + route, body === undefined ? undefined : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const data = await response.json(); assert.equal(response.status, expected, `${route}: ${JSON.stringify(data)}`); return data;
  };
  const start = async () => {
    server = spawn(process.execPath, [path.resolve('dist/server.cjs')], { env: { ...process.env, APP_ROOT: root, NODE_ENV: 'production', PORT: String(port) }, stdio: 'ignore', windowsHide: true });
    for (let i = 0; i < 150; i++) {
      try { const scan = await request('/api/library/scan-status'); if (!scan.scanning) return; } catch { /* Starting. */ }
      await new Promise(resolve => setTimeout(resolve, 100));
    }
    throw new Error('Isolated server did not start');
  };
  const stop = async () => { if (server.exitCode === null) { const exited = new Promise(resolve => server.once('exit', resolve)); server.kill(); await exited; } };
  try {
    await start();
    let books = await request('/api/library');
    assert.equal(books.length, 1); assert.equal(books[0].rootType, 'inbox'); assert.equal(books[0].processingStatus, 'incomplete');
    assert.equal(books[0].identificationWarning, undefined);
    const unchanged = JSON.stringify(readProjectState(root));
    await request('/api/library/refresh', {});
    assert.equal(JSON.stringify(readProjectState(root)), unchanged, 'unchanged files reuse the saved metadata cache');
    assert.equal((await request('/api/jobs/existing-book')).canMoveToLibrary, false);
    const config = await request('/api/config');
    assert.equal(config.quick_tags.length, 50, 'older settings receive the initial Quick Tags');
    await request('/api/config', { quick_tags: ['Cosmic Horror', ' cosmic   horror ', 'Fantasy'] });
    assert.deepEqual((await request('/api/config')).quick_tags, ['Cosmic Horror', 'Fantasy']);
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(root, 'config.json'), 'utf8')).quick_tags, ['Cosmic Horror', 'Fantasy']);
    await request('/api/config', { quick_tags: ['Cosmic Horror'] });
    assert.deepEqual((await request('/api/config')).quick_tags, ['Cosmic Horror'], 'deleted defaults stay deleted');
    assert.deepEqual((await request('/api/jobs/existing-book')).metadata.tags, ['Keep'], 'deleting a suggestion does not rewrite book tags');
    await request('/api/config', { quick_tags: ['Renamed Horror'] });
    assert.deepEqual((await request('/api/jobs/existing-book')).metadata.tags, ['Keep'], 'renaming a suggestion does not rewrite book tags');
    await request('/api/config', { quick_tags: ['Cosmic Horror'] });
    const otherInbox = path.join(root, 'Other Inbox');
    await request('/api/config', { inbox_folder: otherInbox });
    assert.equal((await request('/api/config')).library_folder, library);
    await request('/api/config', { inbox_folder: inbox });
    await request('/api/config', { inbox_folder: library }, 400);
    await request('/api/config', { inbox_folder: 'relative/not-allowed' }, 400);
    assert.equal((await request('/api/config')).inbox_folder, inbox);
    assert.equal(config.library_template, '%Book Title%');
    const unknown = path.join(inbox, 'Unknown'); fs.mkdirSync(unknown); fs.copyFileSync(audio, path.join(unknown, 'part.m4b'));
    books = (await request('/api/library/refresh', {})).books;
    assert.equal(books.length, 2); assert.match(books.find((book: any) => book.name === 'Unknown').identificationWarning, /folder name/);
    const unknownId = books.find((book: any) => book.name === 'Unknown').id;
    fs.copyFileSync(audio, path.join(unknown, 'excluded.m4b'));
    await request(`/api/jobs/${unknownId}/source-files`, { action: 'include', files: ['excluded.m4b'] });
    await request(`/api/jobs/${unknownId}/source-files`, { action: 'remove', files: ['excluded.m4b'] });
    fs.copyFileSync(audio, path.join(unknown, 'new-unowned.m4b'));
    await request('/api/library/rescan', {});
    assert.deepEqual((await request(`/api/jobs/${unknownId}`)).parts.map((part: any) => part.name), ['part.m4b'], 'Library rescan preserves unprocessed project membership and exclusions');
    const movedUnknown = path.join(library, 'Relocated'); fs.renameSync(unknown, movedUnknown);
    books = (await request('/api/library/refresh', {})).books;
    assert.equal(books.find((book: any) => book.id === unknownId).rootType, 'library', 'manual relocation preserves ID');
    fs.rmSync(movedUnknown, { recursive: true });
    assert.equal((await request('/api/library/refresh', {})).books.filter((book: any) => !book.sourceMissing).length, 1);
    assert.ok((await request(`/api/jobs/${unknownId}`)).sourceMissing, 'missing records remain recoverable');
    const checked = await request('/api/jobs/existing-book/validate', {});
    assert.equal(checked.validation.status, 'PASS', JSON.stringify(checked.validation));
    assert.equal((await request('/api/library')).find((book:any)=>book.id==='existing-book').processingStatus, 'complete');
    assert.equal((await request('/api/jobs/existing-book')).canMoveToLibrary, true);
    const unrelated = path.join(source, 'unrelated.m4b'); fs.copyFileSync(audio, unrelated);
    await request('/api/jobs/existing-book/move-to-library', {}, 400);
    assert.ok(fs.existsSync(audio)); assert.ok(fs.existsSync(unrelated));
    fs.unlinkSync(unrelated);
    const destination = path.join(library, meta.title); fs.mkdirSync(destination); fs.writeFileSync(path.join(destination, 'keep.txt'), 'Never overwrite');
    await request('/api/jobs/existing-book/move-to-library', { mode: 'move' }, 409);
    assert.ok(fs.existsSync(audio)); assert.equal(fs.readFileSync(path.join(destination, 'keep.txt'), 'utf8'), 'Never overwrite');
    fs.rmSync(destination, { recursive: true });
    // Force a persistence failure after destination verification; source and paths roll back.
    const allowWrites=rejectProjectWrites(root);
    await request('/api/jobs/existing-book/move-to-library', { mode: 'move' }, 409);
    assert.ok(fs.existsSync(audio)); assert.equal(fs.existsSync(destination), false);
    assert.equal((await request('/api/jobs/existing-book')).source.path, source);
    allowWrites();
    // Rollback may restore files with new stamps; verify the restored project
    // again instead of relying on a pre-transfer Final Check signature.
    const restoredCheck = await request('/api/jobs/existing-book/validate', {});
    assert.equal(restoredCheck.validation.status, 'PASS', JSON.stringify(restoredCheck.validation));
    const result = await request('/api/jobs/existing-book/move-to-library', { mode: 'move' });
    assert.equal(fs.existsSync(source), false); assert.ok(fs.existsSync(path.join(destination, 'original.m4b')));
    assert.ok(fs.existsSync(path.join(destination, 'finished.m4b')));
    assert.equal(result.job.source.path, destination); assert.equal(result.job.outputM4b.fullPath, path.join(destination, 'finished.m4b'));
    assert.equal(result.job.exportedFiles.m4b, result.job.outputM4b.fullPath);
    assert.equal(result.job.metadataDraft.description, 'Unfinished draft');
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(destination, 'metadata.json'), 'utf8')), meta, 'existing compatibility sidecar remains untouched when compatibility is off');
    assert.equal(JSON.parse(fs.readFileSync(path.join(destination,'exmetadata.json'),'utf8')).metadata.title,meta.title);
    assert.equal(JSON.parse(fs.readFileSync(path.join(destination, 'metadata.json'), 'utf8')).title, meta.title, 'root sidecar describes the saved book');
    assert.equal(result.job.canMoveToLibrary, false);
    books = (await request('/api/library/refresh', {})).books;
    assert.equal(books.filter((book: any) => !book.sourceMissing).length, 1); assert.equal(books[0].id, job.id); assert.equal(books[0].rootType, 'library'); assert.equal(books[0].processingStatus, 'complete');
    assert.equal((await request('/api/jobs/existing-book')).parts.length, 1, 'finished exports do not become duplicate source parts');
    const movedOriginal = path.join(destination, 'original.m4b');
    fs.unlinkSync(movedOriginal);
    const rescanned = await request('/api/library/rescan', {});
    assert.equal(rescanned.recovered, 1);
    assert.equal(rescanned.books.filter((book: any) => !book.sourceMissing).length, 1);
    assert.equal(rescanned.books[0].rootType, 'library');
    assert.equal(rescanned.books[0].sourceMissing, false);
    assert.equal(rescanned.books[0].originalSourceMissing, true);
    assert.equal(rescanned.books[0].availableM4bPath, path.join(destination, 'finished.m4b'));
    assert.equal((await request('/api/jobs/existing-book')).sourceMissing, true, 'processing still knows its original source is absent');
    assert.equal((await request('/api/jobs/existing-book')).metadataDraft.description, 'Unfinished draft');
    assert.ok(fs.existsSync(path.join(destination, 'finished.m4b')), 'rescan does not move the export');
    fs.writeFileSync(movedOriginal, originalBytes);
    await request('/api/library/refresh', {});
    await stop(); await start();
    assert.equal((await request('/api/config')).inbox_folder, inbox);
    assert.deepEqual((await request('/api/config')).quick_tags, ['Cosmic Horror'], 'Quick Tags survive restart');
    assert.equal((await request('/api/library'))[0].processingStatus, 'incomplete', 'removing an original invalidates the prior completion check');
    fs.appendFileSync(path.join(destination, 'original.m4b'), 'changed');
    assert.equal((await request('/api/library/refresh', {})).books[0].processingStatus, 'incomplete');
    fs.writeFileSync(path.join(destination, 'metadata.json'), JSON.stringify({ ...meta, author: 'Updated on disk' }));
    assert.equal((await request('/api/library/refresh', {})).books[0].metadata.author, meta.author, 'extended sidecar wins over an edited compatibility sidecar');
    const extended=JSON.parse(fs.readFileSync(path.join(destination,'exmetadata.json'),'utf8'));extended.fileTags.author='Updated on disk';delete extended.fileTags.authors;delete extended.metadata.authors;
    fs.writeFileSync(path.join(destination,'exmetadata.json'),JSON.stringify(extended));
    assert.equal((await request('/api/library/refresh', {})).books[0].metadata.author, 'Updated on disk');
    assert.equal((await request('/api/jobs/existing-book')).metadataDraft.description, 'Unfinished draft');
    const offline = library + '-offline'; fs.renameSync(library, offline);
    const unavailable = await request('/api/library/refresh', {});
    assert.ok(unavailable.books.some((book: any) => book.id === job.id), 'temporarily unavailable roots retain records');
    assert.match(unavailable.warnings.join(' '), /unavailable/);
    fs.renameSync(offline, library);
    fs.writeFileSync(movedOriginal, originalBytes);
    await request('/api/library/refresh', {});
    const savedBeforeReorganization = await request('/api/jobs/existing-book');
    await writeAudioMetadata({ ffmpeg, ffprobe, file: savedBeforeReorganization.outputM4b.fullPath, format: 'm4b', tags: audiobookTags(savedBeforeReorganization.metadata, undefined, {}, 'm4b') });
    fs.writeFileSync(path.join(destination, 'exmetadata.json'), JSON.stringify(extendedMetadata(savedBeforeReorganization.metadata, savedBeforeReorganization.chapters, job.id)));
    await request('/api/library/refresh', {});
    const beforeReorganization = await request('/api/jobs/existing-book/validate', {});
    assert.equal(beforeReorganization.validation.status, 'PASS', JSON.stringify(beforeReorganization.validation));
    assert.equal((await request('/api/jobs/existing-book')).processingStatus, 'complete', 'fixture must be complete before a same-file move');
    await stop();
    const recoverySource = path.join(inbox, 'Recover interrupted book');
    const recoveryCopy = path.join(inbox, '.swissmouse-test.moved');
    const recoveryTarget = path.join(library, 'Uncommitted destination');
    fs.mkdirSync(recoveryCopy); fs.mkdirSync(recoveryTarget);
    fs.writeFileSync(path.join(recoveryCopy, 'book.m4b'), 'Original preserved');
    fs.writeFileSync(path.join(recoveryTarget, 'book.m4b'), 'Verified copy preserved');
    const records = readProjectState(root);
    records.push({ ...job, id: 'recover-book', source: { kind: 'inbox', mode: 'folder', path: recoverySource }, sourceFolderPath: recoverySource, parts: [{ ...job.parts[0], name: 'book.m4b' }], outputM4b: null, exports: [], exportedFiles: {}, metadata: { ...meta, title: 'Recover interrupted book' } });
    writeProjectState(root,records);
    fs.writeFileSync(path.join(root, 'library-move-recovery.json'), JSON.stringify({ id: 'recover-book', source: recoverySource, quarantine: recoveryCopy, target: recoveryTarget }));
    await start();
    assert.equal(fs.readFileSync(path.join(recoverySource, 'book.m4b'), 'utf8'), 'Original preserved');
    assert.equal(fs.existsSync(recoveryTarget), false);
    const retained = fs.readdirSync(library).find(name => name.startsWith('.swissmouse-recovered-'))!;
    assert.equal(fs.readFileSync(path.join(library, retained, 'book.m4b'), 'utf8'), 'Verified copy preserved');
    assert.equal((await request('/api/library')).filter((book: any) => book.id === 'recover-book').length, 1);
    const tree = await request('/api/jobs/existing-book/source-tree');
    assert.equal(tree.root, destination);
    assert.ok(tree.entries.some((entry: any) => entry.relativePath === 'original.m4b'));
    await request('/api/jobs/existing-book/source-files', { action: 'create-folder', parent: '', name: 'Disc 2' });
    const reorganized = await request('/api/jobs/existing-book/source-files', { action: 'move', files: ['original.m4b'], destination: 'Disc 2' });
    assert.equal(reorganized.job.parts[0].sourceRelativePath, 'Disc 2/original.m4b');
    assert.equal(reorganized.job.sourceFilesChanged, undefined, 'moving the same file in place does not stale processing');
    assert.equal(reorganized.job.sourcePathIdentity['Disc 2/original.m4b'], path.join(destination, 'original.m4b'));
    assert.equal(reorganized.job.sourceKey, result.job.sourceKey, 'same-file move preserves the processed source key');
    assert.equal(reorganized.job.processingStatus, 'complete', 'move keeps processing status');
    assert.equal(reorganized.job.sourceReorganizationPending, true);
    assert.equal(await fingerprint([path.join(destination, 'Disc 2', 'original.m4b')], {}, [path.join(destination, 'original.m4b')]), result.job.sourceKey);
    assert.equal((await request('/api/library/refresh', {})).books[0].processingStatus, 'complete', 'same-file reorganization keeps the completed book current');
    const movedValidation = await request('/api/jobs/existing-book/validate', {});
    assert.equal(movedValidation.validation.status, 'PASS', `final validation recognizes the moved source: ${movedValidation.validation.reason}`);
    const detached = await request('/api/jobs/existing-book/source-files', { action: 'remove', files: ['Disc 2/original.m4b'] });
    assert.equal(detached.job.parts.length, 0, 'a validated M4B can be kept without its original source in the manifest');
    assert.equal(detached.job.validation.status, 'PASS');
    assert.ok(fs.existsSync(path.join(destination, 'Disc 2', 'original.m4b')), 'manifest removal leaves the original on disk');
    const restoredSource = await request('/api/jobs/existing-book/source-files', { action: 'include', files: ['Disc 2/original.m4b'] });
    assert.equal(restoredSource.job.parts.length, 1);
    assert.ok(fs.existsSync(path.join(destination, 'Disc 2', 'original.m4b')));
    assert.ok(fs.existsSync(path.join(destination, 'finished.m4b')));
    const outsideMove = await fetch(base + '/api/jobs/existing-book/source-files', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'move', files: ['Disc 2/original.m4b'], destination: '..' }) });
    assert.equal(outsideMove.status, 400);
    assert.ok(fs.existsSync(path.join(destination, 'Disc 2', 'original.m4b')));
    const extra = path.join(root, 'extra.m4b'); fs.copyFileSync(path.join(destination, 'Disc 2', 'original.m4b'), extra);
    const added = await request('/api/jobs/existing-book/source-files', { action: 'add', file: extra, destination: '' });
    assert.equal(added.job.parts.length, 2);
    assert.equal(added.job.sourceFilesChanged, true);
    assert.ok(added.job.staleSteps.includes('export'));
    assert.ok(fs.existsSync(extra), 'adding copies and preserves the chosen original');
    assert.ok(fs.existsSync(path.join(destination, 'extra.m4b')));
    const ordered = await request('/api/jobs/existing-book/source-files', { action: 'reorder', files: ['extra.m4b', 'Disc 2/original.m4b'] });
    assert.deepEqual(ordered.order, ['extra.m4b', 'Disc 2/original.m4b']);
    assert.equal(ordered.job.sourceOrderManual, true);
    const removed = await request('/api/jobs/existing-book/source-files', { action: 'remove', files: ['extra.m4b'] });
    assert.equal(removed.job.parts.length, 1);
    assert.ok(fs.existsSync(path.join(destination, 'extra.m4b')), 'removing from project does not delete audio');
    const refreshed = await request('/api/jobs/existing-book/source-files', { action: 'refresh' });
    assert.equal(refreshed.job.parts.length, 1, 'rescan respects explicit manifest exclusions');
    const included = await request('/api/jobs/existing-book/source-files', { action: 'include', files: ['extra.m4b'] });
    assert.equal(included.job.parts.length, 2);
    assert.deepEqual(included.order, ['Disc 2/original.m4b', 'extra.m4b']);
    fs.copyFileSync(extra, path.join(destination, 'fresh.m4b'));
    const discovered = await request('/api/jobs/existing-book/source-files', { action: 'refresh' });
    assert.deepEqual(discovered.order, ['Disc 2/original.m4b', 'extra.m4b']);
    assert.ok(discovered.entries.some((entry: any) => entry.relativePath === 'fresh.m4b' && !entry.included));
    assert.ok(discovered.entries.some((entry: any) => entry.relativePath === 'finished.m4b' && !entry.included), 'rescan keeps export out of the source manifest');
    const repeated = await request('/api/jobs/existing-book/source-files', { action: 'refresh' });
    assert.deepEqual(repeated.order, discovered.order, 'repeated refresh preserves membership without duplicates');
    fs.unlinkSync(path.join(destination, 'Disc 2', 'original.m4b'));
    const metadataConflict = await request('/api/jobs/existing-book/metadata', { metadata: { ...meta, title: 'Verified Book Revised' } }, 500);
    assert.match(metadataConflict.error, /metadata.json was not changed/, 'root sidecar remains protected when unrelated audio shares the folder');
    const organize = await request('/api/jobs/existing-book/organize-library');
    assert.equal(organize.mode, 'move');
    assert.equal(organize.folder, true, 'a managed book with missing source audio keeps its full folder');
    const organized = await request('/api/jobs/existing-book/organize-library', { source: organize.source, target: organize.target });
    assert.equal(organized.job.source.path, organize.target);
    assert.ok(fs.existsSync(path.join(organize.target, 'finished.m4b')));
    assert.equal(fs.existsSync(path.join(organize.target, 'Disc 2')), false, 'missing parts do not create empty copied folders');
    assert.ok(fs.existsSync(path.join(destination, 'fresh.m4b')), 'unassociated audio and its nonempty folder remain in place');
    assert.equal((await request('/api/jobs/existing-book')).sourceMissing, true, 'organizing does not pretend the original audio returned');
    const log = fs.readFileSync(path.join(root, 'logs', 'workbench-events.jsonl'), 'utf8');
    assert.match(log, /verification passed/); assert.match(log, /Move failed/); assert.match(log, /Move success/);
    assert.match(log, /Interrupted move restored to Inbox/);
  } finally { if (server!) await stop(); assert.ok(root.startsWith(process.cwd() + path.sep)); fs.rmSync(root, { recursive: true, force: true }); }
});
