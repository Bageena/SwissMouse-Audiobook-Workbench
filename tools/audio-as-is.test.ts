import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
import { createTestFixture, stopTestServer } from './test-fixtures.mjs';
import { inspect } from './audio-engine';
import { readProjectState } from './project-store-fixture';

test('as-is audio supports embedded chapters, manual review, multipart CUE, export and completion', {timeout:60000}, async t => {
  const fixture = createTestFixture('.cache/audio-as-is-'); const {root} = fixture;
  t.after(()=>fixture.cleanup());
  const bin = path.join(root,'runtime/bin'); fs.mkdirSync(bin,{recursive:true});
  const binary = (name:string)=>name+(process.platform==='win32'?'.exe':'');
  for (const name of ['ffmpeg','ffprobe']) fs.copyFileSync(process.env['TEST_'+name.toUpperCase()] || path.resolve('runtime/bin',binary(name)),path.join(bin,binary(name)));
  const ffmpeg = path.join(bin,binary('ffmpeg')), ffprobe=path.join(bin,binary('ffprobe'));
  const source = path.join(root,'Retail.m4b'); const markers=path.join(root,'chapters.ffmeta');
  fs.writeFileSync(markers,';FFMETADATA1\ntitle=Retail\n[CHAPTER]\nTIMEBASE=1/1000\nSTART=0\nEND=3000\ntitle=OPENING\n[CHAPTER]\nTIMEBASE=1/1000\nSTART=3000\nEND=6000\ntitle=SECOND CHAPTER\n');
  execFileSync(ffmpeg,['-v','error','-f','lavfi','-i','sine=duration=6','-i',markers,'-map','0:a','-map_metadata','1','-map_chapters','1','-c:a','aac',source],{windowsHide:true});
  const original=fs.readFileSync(source);
  const port=27000+Math.floor(Math.random()*2000), base=`http://127.0.0.1:${port}`;
  const server=spawn(process.execPath,[path.resolve('dist/server.cjs')],{env:{...process.env,APP_ROOT:root,PORT:String(port),NODE_ENV:'production',SWISSMOUSE_RUNTIME_MODE:'managed'},windowsHide:true,stdio:'pipe'});
  let logs='';server.stdout.on('data',d=>logs+=d);server.stderr.on('data',d=>logs+=d);
  const request=async(route:string,body?:unknown)=>{
    const response=await fetch(base+route,body===undefined?undefined:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
    const data:any=await response.json();assert.ok(response.ok,route+': '+JSON.stringify(data)+'\n'+logs);return data;
  };
  const wait=async()=>{for(let i=0;i<200;i++){const progress=await request('/api/step1/progress');if(!progress.isActive){assert.equal(progress.error,null,JSON.stringify(progress));return;}await new Promise(r=>setTimeout(r,50));}assert.fail('Processing timeout');};
  try {
    for(let i=0;i<150&&!logs.includes('server running');i++)await new Promise(r=>setTimeout(r,100));
    assert.match(logs,/server running/);
    const book=await request('/api/jobs',{name:'Retail',author:'Writer',narrator:'Reader',parts:[{name:source}]}); const route='/api/jobs/'+book.id;
    await request(route+'/process-step1',{mergeMethod:'skip',chapterSource:'existing_chapters'}); await wait();
    let saved=await request(route);
    assert.equal(saved.mergedMp3.fullPath,source); assert.equal(saved.previewPath,undefined);
    assert.equal(saved.generateWaveform,false);
    assert.equal((await fetch(base+route+'/waveform?start=0&duration=6&pixels=100')).status,404,'waveform requests do not create optional data');
    assert.equal(saved.existingChapterSource,'Embedded chapters'); assert.equal(saved.chapters.length,2);
    assert.deepEqual(fs.readFileSync(source),original);
    assert.ok((await fetch(base+route+'/audio-preview')).ok,'single-file review streams the source');
    await request(route+'/process-step1',{mergeMethod:'skip',chapterSource:'existing_chapters',generateWaveform:true});await wait();
    saved=await request(route);assert.equal(saved.waveformReady,true);
    assert.ok((await request(route+'/waveform?start=0&duration=6&pixels=100')).peaks.length);
    await request(route+'/step1-settings',{generateWaveform:false});
    assert.equal((await fetch(base+route+'/waveform?start=0&duration=6&pixels=100')).status,404);
    const reviewed=saved.chapters.map((chapter:any,index:number)=>({...chapter,title:index?'Second chapter':'Opening',titleManuallyEdited:true}));
    await request(route+'/chapters',{chapters:reviewed});
    const savedEdits = (await request(route)).chapters;
    await request(route+'/process-step1',{mergeMethod:'skip',chapterSource:'manual'}); await wait();
    saved=await request(route);assert.deepEqual(saved.chapters,savedEdits,'manual route preserves edits');
    const exported=await request(route+'/build-m4b',{outputFormats:['m4b']});
    assert.equal(exported.exports[0].status,'success',JSON.stringify(exported));
    assert.match(exported.exports[0].mode,/copy/i,'retail audio is remuxed without encoding');
    assert.equal(inspect(ffprobe,exported.exports[0].fullPath).chapters[1].title,'Second chapter');
    assert.equal((await request(route+'/validate',{})).validation.status,'PASS');
    assert.equal((await request(route)).processingStatus,'complete');
    assert.deepEqual(fs.readFileSync(source),original,'metadata-only finish preserves its source');

    const imported=await request(route+'/chapter-file',{name:'chosen-chapters.txt',content:'00:00:00.000 Imported opening\n00:00:03.000 Imported second'});
    assert.equal(imported.count,2);
    assert.equal(readProjectState(root).find((item:any)=>item.id===book.id).importedChapterFile.name,'chosen-chapters.txt','selected chapter source is persisted with the project');
    assert.deepEqual((await request(route)).chapters,savedEdits,'selecting an imported source does not overwrite reviewed chapters');
    assert.match((await request(route+'/existing-chapters')).source,/Imported chapters/);
    await request(route+'/process-step1',{mergeMethod:'skip',chapterSource:'existing_chapters'});await wait();
    assert.deepEqual((await request(route)).chapters.map((chapter:any)=>chapter.title),['Imported opening','Imported second'],'explicit import overrides embedded markers');
    const invalid=await fetch(base+route+'/chapter-file',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'wrong.m3u',content:'https://example.com/unrelated.mp3'})});
    assert.equal(invalid.status,400);
    assert.equal((await request(route)).importedChapterFile.name,'chosen-chapters.txt','invalid imports retain the previous selected source');
    assert.ok((await fetch(base+route+'/chapter-file',{method:'DELETE'})).ok);
    assert.equal((await request(route+'/existing-chapters')).source,'Embedded chapters');

    const partsDir=path.join(root,'Multipart');fs.mkdirSync(partsDir);
    const files=['one.wav','two.wav'].map(name=>path.join(partsDir,name));
    for(const file of files)execFileSync(ffmpeg,['-v','error','-f','lavfi','-i','sine=duration=2',file],{windowsHide:true});
    const bytes=files.map(file=>fs.readFileSync(file));
    fs.writeFileSync(path.join(partsDir,'chapters.cue'),'FILE "one.wav" WAVE\n TRACK 01 AUDIO\n TITLE "One"\n INDEX 01 00:00:00\nFILE "two.wav" WAVE\n TRACK 02 AUDIO\n TITLE "Two"\n INDEX 01 00:00:00\n');
    const multi=await request('/api/jobs',{name:'Multipart',parts:files.map(name=>({name}))});const multiRoute='/api/jobs/'+multi.id;
    await request(multiRoute+'/process-step1',{mergeMethod:'skip',chapterSource:'existing_chapters'});await wait();
    const ready=await request(multiRoute);
    assert.deepEqual(ready.chapters.map((chapter:any)=>[chapter.title,chapter.start]),[['One','00:00:00.000'],['Two','00:00:02.000']]);
    assert.equal(fs.existsSync(ready.mergedMp3.fullPath),false,'no full-quality master is created during skip');
    assert.ok(fs.existsSync(ready.previewPath),'multipart review gets a lightweight preview');
    assert.equal(ready.waveformReady,false);
    assert.equal(fs.existsSync(ready.previewPath+'.analysis.json'),false,'multipart playback does not generate waveform data when unchecked');
    assert.deepEqual(files.map(file=>fs.readFileSync(file)),bytes);
    const playlist=await request(multiRoute+'/chapter-file',{name:'book.m3u8',content:'#EXTM3U\n#EXTINF:999,Playlist one\none.wav\n#EXTINF:999,Playlist two\ntwo.wav'});
    assert.equal(playlist.kind,'tracks');
    await request(multiRoute+'/process-step1',{mergeMethod:'skip',chapterSource:'existing_chapters'});await wait();
    assert.deepEqual((await request(multiRoute)).chapters.map((chapter:any)=>[chapter.title,chapter.start]),[['Playlist one','00:00:00.000'],['Playlist two','00:00:02.000']],'playlist uses measured durations rather than EXTINF estimates');
    const finished=await request(multiRoute+'/build-m4b',{outputFormats:['wav']});
    assert.equal(finished.exports[0].status,'success',JSON.stringify(finished));
    assert.ok(Math.abs(inspect(ffprobe,finished.exports[0].fullPath).durationSeconds-4)<0.1);
    assert.deepEqual(files.map(file=>fs.readFileSync(file)),bytes,'joining at export preserves originals');
    const currentChapters=(await request(multiRoute)).chapters;
    fs.appendFileSync(files[0],Buffer.from([0]));
    const changed=await request(multiRoute+'/existing-chapters');
    assert.equal(changed.count,0,'an imported playlist cannot silently follow changed audio');
    assert.match(changed.source,/no longer matches/);
    assert.deepEqual((await request(multiRoute)).chapters,currentChapters,'stale imported sources preserve reviewed chapter edits');
  } finally { await stopTestServer(server); }
});
