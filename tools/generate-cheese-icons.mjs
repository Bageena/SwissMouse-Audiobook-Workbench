function makeSvg(name, geometry, filled = false) {
  const color = /Alert|CircleX|XCircle|Trash/.test(name) ? '#b36450' : /Check/.test(name) ? '#718451' : '#b79148';
  const paper = /Alert|CircleX|XCircle|Trash/.test(name) ? '#f0d2bd' : /Check/.test(name) ? '#dce3c4' : '#eddbb5';
  // Closed silhouettes become paper cutouts; open arrows, grips, and strokes
  // stay open so their familiar meaning remains clear at control sizes.
  geometry = geometry.replace(/<(circle|rect|polygon|path)\b([^>]*?)\/>/g, (tag, kind, attributes) => {
    const d = attributes.match(/\bd="([^"]+)"/)?.[1] ?? '';
    const closed = kind !== 'path' || /[zZ](?:\s*[mM]|\s*$)/.test(d);
    return closed && !/\bfill=/.test(attributes) ? `<${kind}${attributes} fill="${filled ? '#e7b94d' : paper}"/>` : tag;
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-3 -3 30 30" fill="none"><title>Paper and Ink: ${escape(name)}</title><defs><pattern id="hatch" width="5" height="5" patternUnits="userSpaceOnUse" patternTransform="rotate(32)"><path d="M0 0v5M3 1v2" stroke="#514633" stroke-width=".4" opacity=".15"/></pattern><g id="ink" stroke-linecap="round" stroke-linejoin="round">${geometry}</g><mask id="shape" style="mask-type:alpha"><use href="#ink" fill="${filled ? color : '#fff2d6'}" stroke="white" stroke-width="1.7"/></mask></defs><use href="#ink" fill="none" stroke="#fff2d6" stroke-width="4.4"/><use href="#ink" fill="${filled ? '#e7b94d' : 'none'}" stroke="${/Alert|Check|CircleX|XCircle/.test(name) ? color : '#494236'}" stroke-width="1.65"/><rect x="-2" y="-2" width="28" height="28" fill="url(#hatch)" mask="url(#shape)"/></svg>`;
}
