function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(item => item.isDirectory() ? walk(path.join(dir, item.name)) : [path.join(dir, item.name)]);
}
const used = new Set();
for (const file of walk('src').filter(file => /\.tsx?$/.test(file))) {
  const source = fs.readFileSync(file, 'utf8');
  for (const match of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"]lucide-react['"]/g)) {
    for (const item of match[1].split(',')) {
      const name = item.trim().split(/\s+as\s+/)[0];
      if (name) used.add(name);
    }
  }
  for (const match of source.matchAll(/import\s*\*\s*as\s+(\w+)\s+from\s*['"]lucide-react['"]/g)) {
    for (const reference of source.matchAll(new RegExp(`\\b${match[1]}\\.(\\w+)`, 'g'))) {
      if (lucide[reference[1]]) used.add(reference[1]);
    }
  }
}
